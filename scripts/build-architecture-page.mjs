// Build the texts the architecture page shows beside its boxes (Ran, 24.10.2026):
//
//   "תוסיף לדשבורד של הארכיטקטורה את הוראות הראיון — הכלליות: בצמוד לכפתורים של
//    כל סוג ראיון; עבור כל מראיין: בסמוך לריבוע שמציג את המראיין והסלוטים שלו";
//   "ליד ה-Router לשים את ההגדרות של הפעולה של ה-Router";
//   "ליד הרשם לשים את הגדרות הפעולה של הרשם".
//
//   node scripts/build-architecture-page.mjs [docs/architecture-v3.html]
//
// Reads the repo — the guidelines as guidelines.js composes them (head and tail),
// each stage agent and each registrar as src/packs/text.js hands them to the model
// (version headers stripped), and the packs' routing data — and rewrites ONE block
// in the page, between the markers below, as a JSON script the page's own code
// renders into expandable panels. The page stays hand-written; only this block is
// generated, so a prompt or pack change is: rerun, republish.
//
// Which text belongs to which interview is read from each pack's prompts.js (the
// `?raw` imports), never guessed from file names — the mapping is prompt-editor's
// and this script follows it.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { checkGuidelines } from '../src/core/guidelines.js';
import { text } from '../src/packs/text.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const BEGIN = '<!-- arch-texts:begin — generated by scripts/build-architecture-page.mjs; do not edit by hand -->';
const END = '<!-- arch-texts:end -->';

// The `?raw` imports of a pack's prompts.js: { importName: 'src/content/prompts/…' }.
function rawImports(packDir) {
  const src = read(`src/packs/${packDir}/prompts.js`);
  const out = {};
  for (const m of src.matchAll(/import\s+(\w+)\s+from\s+'([^']+)\?raw'/g)) {
    out[m[1]] = resolve(join(root, `src/packs/${packDir}`), m[2]).slice(root.length + 1);
  }
  // Which imports stand behind each stage key, in order: `stage1: text(stage1)`,
  // or a composition such as `stage3: text(stage3) + '\n\n' + text(catalog)` (the
  // parents' pack appends its catalog to some stages). Everything `text(...)`
  // names inside the value is what the model reads for that stage.
  const stages = {};
  const block = src.slice(src.indexOf('stages:'));
  for (const m of block.matchAll(/(stage\d+):\s*([\s\S]*?)(?=,\s*\n\s*stage\d+:|,?\s*\n\s*\})/g)) {
    const names = [];
    for (const call of m[2].matchAll(/(\w+)\((\w+)\)/g)) {
      names.push(call[2]);
      // `withCatalog(stageN)` (the parents' pack) appends the catalog text.
      if (call[1] === 'withCatalog' && out.catalog) names.push('catalog');
    }
    stages[m[1]] = names.filter((n) => out[n]);
  }
  return { files: out, stages };
}

// What each slot holds, as the stage agent tells the model: the bullet lines
// "- slot: …" under its "מה לחקור" list (Ran, 24.10.2026: "ליד כל סלוט בכל מראיין
// לכתוב את תכולת הסלוט"). A slot the agent does not describe gets ''.
function slotDocs(agentText) {
  const docs = {};
  for (const m of agentText.matchAll(/^\s*[-*]\s*`?([a-z_]+)`?\s*[:：—–-]\s*(.+)$/gm)) {
    if (!(m[1] in docs)) docs[m[1]] = m[2].trim();
  }
  return docs;
}

async function pack(dir) {
  const mod = await import(`../src/packs/${dir}/pack.js`);
  const p = Object.values(mod).find((v) => v && typeof v === 'object' && Array.isArray(v.stages));
  const { files, stages } = rawImports(dir);
  const superMd = read(files.guidelinesSuper);
  const specificMd = read(files.guidelinesSpecific);
  const g = checkGuidelines({ super: superMd, specific: specificMd });
  if (!g.ok) throw new Error(`${dir}: guidelines do not compose — ${g.errors.join('; ')}`);
  const agents = {};
  for (const st of p.stages) {
    const names = stages[st.key] ?? [];
    if (!names.length || names.some((n) => !files[n])) throw new Error(`${dir}: no agent text mapped for ${st.key} (${names.join(', ') || 'nothing'})`);
    agents[st.key] = { files: names.map((n) => files[n]), text: names.map((n) => text(read(files[n]))).join('\n\n') };
  }
  const registrar = files.registrar ? { file: files.registrar, text: text(read(files.registrar)) } : null;
  return {
    id: p.id,
    name: p.name,
    version: p.version,
    routing: p.routing,
    castClarity: p.components?.find?.((c) => c.type === 'castClarity') ?? p.stages.flatMap((s) => s.components ?? []).find((c) => c.type === 'castClarity') ?? null,
    stages: p.stages.map((st, i) => ({
      n: i + 1,
      key: st.key,
      name: st.name,
      label: st.label,
      slots: (st.slots ?? []).map((sl) => ({
        id: sl.id,
        barred: !!sl.barred,
        mental: !!sl.mental,
        core: sl.core !== false,
        doc: slotDocs(agents[st.key].text)[sl.id] ?? '',
      })),
      loadGuard: st.loadGuard ?? null,
      requires: st.requires ?? [],
      components: (st.components ?? []).map((c) => c.type),
    })),
    guidelines: { super: files.guidelinesSuper, specific: files.guidelinesSpecific, head: g.text, tail: g.tail },
    agents,
    registrar,
    evaluator: files.evaluator ? { file: files.evaluator, chars: text(read(files.evaluator)).length } : null,
  };
}

const page = process.argv[2] ?? 'docs/architecture-v3.html';
const data = {
  builtFrom: 'the branch this script ran on',
  packs: { adult: await pack('think-twice-adult'), parents: await pack('think-twice-parents') },
};
const blob = `${BEGIN}\n<script id="arch-texts" type="application/json">${JSON.stringify(data).replace(/<\//g, '<\\/')}</script>\n${END}`;
let html = read(page);
if (html.includes(BEGIN)) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END) + END.length;
  html = html.slice(0, a) + blob + html.slice(b);
} else {
  // First run: the block goes right before the page's own script.
  const i = html.indexOf('<script>');
  if (i < 0) throw new Error('page: no <script> to anchor on');
  html = html.slice(0, i) + blob + '\n' + html.slice(i);
}
writeFileSync(join(root, page), html);
const sizes = Object.entries(data.packs).map(([k, p]) => `${k}: guidelines ${p.guidelines.head.length}+${p.guidelines.tail.length}, ${Object.keys(p.agents).length} agents, registrar ${p.registrar?.text.length ?? 0}`);
console.log(`wrote ${page}: ${blob.length} bytes — ${sizes.join(' · ')}`);
